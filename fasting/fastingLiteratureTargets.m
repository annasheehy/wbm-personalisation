%   id              short key
%   label           human-readable name
%   rxn             model reaction the benchmark maps onto ('' if none/derived)
%   expectDir       'release' | 'uptake' | ''   expected direction at 24 h
%   litLow/litHigh  the band IN MODEL UNITS (mmol/day), NaN if not flux-comparable
%   nativeLow/nativeHigh/nativeUnit   as reported in the source
%   window          which fasting times the band spans
%   source          BibTeX key in the chapter .bib
%   verified        true  = number read directly from the cited source
%                   false = derived/interpolated by us -> CHECK against the paper
%   fluxComparable  false for concentrations/ratios, which must NOT be plotted
