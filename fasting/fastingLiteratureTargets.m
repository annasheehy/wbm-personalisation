function [lo, hi, comparable] = toMmolPerDay(lo, hi, unit, mw, bw)
% Convert a reported rate into mmol/person/day. Concentrations and ratios are NOT
% rates: they come back NaN and flagged not-comparable so no figure can plot them
% against a flux.
comparable = true;
switch unit
    case 'umol/kg/min'          % x kg x 1440 min / 1000
        f = bw * 1.44;          lo = lo * f;  hi = hi * f;
    case 'mg/min/65kg'          % Thiele's exact chain: mg/min -> g/day (weight adj) -> mmol/day
        lo = (lo * 60 * 24 * bw/65)/1000 * 1000/mw;
        hi = (hi * 60 * 24 * bw/65)/1000 * 1000/mw;
    case 'g/day'
        lo = lo * 1000/mw;      hi = hi * 1000/mw;
    case 'mmol/day'
        % already in model units
    otherwise                   % 'mM', 'ratio', 'MJ/day', 'kcal/day', anything else
        lo = NaN;  hi = NaN;    comparable = false;
end
end
