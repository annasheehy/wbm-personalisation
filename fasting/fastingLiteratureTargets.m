%
%   T = fastingLiteratureTargets(bodyWeight)
%   T = fastingLiteratureTargets([], sex)          % sex-default body weight
%
% Returns the quantitative fasting benchmarks the WBM should be compared against,
% converted to the model's units (mmol/person/day) using the SAME conversion
% Thiele 2020 uses inside physiologicalConstraintsHMDBbased.m, e.g.
%
%     % 130 mg glucose/min/person (65 kg), MW 180.16
