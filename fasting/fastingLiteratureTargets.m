% and Harvetta themselves: cite it for the models, the BMR method and the constraint
% machinery, but NEVER as the literature benchmark a model output is judged against -
% that would be testing the models against their own paper. Where a value originates
% in a textbook or primary study that Thiele's code merely encodes (most of the Frayn
% post-absorptive rates), cite that primary source directly. Several of those same
% values are ALSO imposed as bounds in the distributed model, in which case agreement
% is by construction; fastingFigures flags those rows from the FVA range, so the
% circularity is visible rather than claimed as validation.
%
% WHY A BAND, NOT A POINT. A steady-state FBA solution is a DAY-AVERAGED rate, so
% the comparator for the fasted WBM is the flux averaged over an overnight-to-24 h
% fast, not the instantaneous rate at hour 24. Each row therefore carries a range
