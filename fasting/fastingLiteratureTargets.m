% and liver alanine, adipose glycerol ceiling, brain O2), derived from the same
% post-absorptive literature. Where the model flux sits ON such a bound the
% comparison is circular and must be labelled as constrained, not predicted. Use
% fastingCompareToLiterature.m, which checks each flux against its bounds.
%
% Anna Sheehy 2026. Companion to fastingWBM.m / setFastingConstraints.m.

